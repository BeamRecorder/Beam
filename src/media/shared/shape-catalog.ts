const SHAPE_BY_ID = new Map<ShapeKind, ShapeDefinition>(SHAPE_CATALOG.map((definition) => [definition.id, definition]));

export const isShapeKind = (value: unknown): value is ShapeKind =>
  typeof value === 'string' && SHAPE_BY_ID.has(value as ShapeKind);

export const shapeDefinition = (value: ShapeKind) => SHAPE_BY_ID.get(value)!;

export const shapeDisplayName = (value: ShapeKind, locale: string) =>
  locale.toLowerCase().startsWith('fr') ? FRENCH_SHAPE_NAMES[value] : shapeDefinition(value).name;
