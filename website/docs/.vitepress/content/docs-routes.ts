export type DocsLocale = WebsiteLocale;

export const enabledDocsLocales = Object.keys(locales) as DocsLocale[];

export const getDocsCatalogs = (locale: DocsLocale): DocsLocaleCatalogs => {
  const catalogs = locales[locale];
  if (!catalogs) throw new Error(`Documentation locale is not enabled: ${locale}.`);
  return catalogs;
};

export const createDocsRoutes = (locale: DocsLocale) => {
  const content = getDocsCatalogs(locale);
  validateDocsCatalogs(content);
  const prefix = locale === 'en' ? '' : `${locale}/`;
  const localizeInternalLinks = (markdown: string) => {
    if (locale === 'en') return markdown;
    return markdown
      .replaceAll(/\]\(\/(?!\/|docs\/)/g, `](/${prefix}`)
      .replaceAll(/\blink="\/(?!\/|docs\/)/g, `link="/${prefix}`);
  };
  return [
    { params: { page: `${prefix}index` }, content: localizeInternalLinks(renderDocsHome(content.home)) },
    ...content.catalogs.flatMap((catalog) =>
      catalog.pages.map((page) => ({
        params: { page: `${prefix}${page.slug}` },
        content: localizeInternalLinks(renderDocsPage(page)),
      })),
    ),
  ];
};

export const createAllDocsRoutes = () => enabledDocsLocales.flatMap(createDocsRoutes);

export const docsRoutePaths = (locale: DocsLocale = 'en') =>
  createDocsRoutes(locale).map((route) =>
    route.params.page === 'index' ? '/' : route.params.page.replace(/\/index$/, '/'),
  );

export interface DocsSearchEntry {
  title: string;
  description: string;
  path: string;
  text: string;
}

const sectionSearchText = (section: DocsSectionContent): string =>
  [
    section.title,
    ...(section.paragraphs ?? []),
    ...(section.bullets ?? []),
    ...(section.steps ?? []),
    ...(section.tables ?? []).flatMap((table) => [...table.headers, ...table.rows.flat()]),
    section.notice?.title ?? '',
    section.notice?.text ?? '',
    ...(section.subsections ?? []).map(sectionSearchText),
  ].join(' ');

export const getDocsSearchEntries = (locale: DocsLocale): DocsSearchEntry[] => {
  const prefix = locale === 'en' ? '' : `${locale}/`;
  return getDocsCatalogs(locale).catalogs.flatMap((catalog) =>
    catalog.pages.map((page) => ({
      title: page.title,
      description: page.description,
      path: `/${prefix}${page.slug.replace(/\/index$/, '/')}`,
      text: [page.title, page.description, page.lead, ...page.sections.map(sectionSearchText)].join(' '),
    })),
  );
};
